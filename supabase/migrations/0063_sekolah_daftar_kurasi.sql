-- KENAPA DIPASANG SEKARANG, BUKAN DIBIARKAN TUMBUH SENDIRI
--
-- Tanpa ini, tabel `sekolah` terisi dari apa yang diketik pembina di kotak
-- "Asal sekolah" — dan itulah yang melahirkan 36 baris untuk 23 sekolah
-- sebelum 0061. Pagar di 0061 mencegahnya BERLIPAT, tapi tidak membuat baris
-- pertamanya benar: sekolah yang belum ada tetap lahir dari tulisan tangan,
-- lengkap dengan alamat `nan` dan `Jl` tanpa titik.
--
-- Dengan daftar ini terpasang, pembina hampir selalu MEMILIH, bukan mengetik.
-- Itu satu ketukan di HP, bukan satu paragraf alamat — dan alamat yang
-- tersimpan sudah benar sejak baris pertamanya.
--
-- YANG SENGAJA TIDAK IKUT
--
-- - **SMK Nusantara 1 Bekasi** — TIDAK KETEMU, dan kali ini dicari dari sisi ALAMAT, bukan dari nama
-- - **SMPN 1 Kalijaya** — DITAHAN - kandidatnya kuat tapi namanya tidak cocok, jadi sengaja tidak diisikan
--
-- Keduanya sudah disisir dari sisi alamat, bukan cuma dari sisi nama, dan
-- buntu. Memasang tebakan lebih buruk daripada tidak memasang apa-apa:
-- pembina yang tidak menemukan sekolahnya akan mengetiknya sendiri, dan itu
-- jalan yang memang disediakan. Yang menemukan sekolah dengan alamat SALAH
-- tidak akan curiga sama sekali.
--
-- 19 baris berkeyakinan `sedang` IKUT dipasang. Yang `sedang` di sana hampir
-- selalu kode posnya, bukan sekolahnya — nama dan alamat jalannya sudah dari
-- Data Referensi, dan yang berselisih cuma lima angka terakhir antar sumber.
-- Menahan sekolah yang namanya sudah pasti karena satu digit kode pos akan
-- memaksa pembinanya mengetik ulang seluruh alamatnya dari nol, yang justru
-- lebih mungkin salah.
--
-- BISA DIJALANKAN ULANG
--
-- `on conflict do update`, jadi menjalankannya dua kali tidak melahirkan
-- baris kedua — ia hanya menimpa nama dan alamatnya dengan yang sama.
-- Pendaftaran yang sudah menunjuk baris itu tidak tersentuh, karena `id`-nya
-- tidak berubah.
