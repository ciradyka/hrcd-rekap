do $$
declare v_sebelum int; v_sesudah int;
begin
  select count(*) into v_sebelum from sekolah;

  insert into sekolah (name, address)
  select k.nama, k.alamat from sekolah_kurasi k
  on conflict (kunci_sekolah(name)) do update
    set name = excluded.name, address = excluded.address;

  select count(*) into v_sesudah from sekolah;
  raise notice '0063: % sekolah -> % (% baru, % diperbarui).',
    v_sebelum, v_sesudah, v_sesudah - v_sebelum,
    (select count(*) from sekolah_kurasi) - (v_sesudah - v_sebelum);
end $$;

drop table sekolah_kurasi;

do $$
declare v_s int; v_d int; v_tanpa int;
begin
  select count(*) into v_s from sekolah;
  select count(*) into v_d from (
    select 1 from sekolah group by kunci_sekolah(name) having count(*) > 1) x;
  select count(*) into v_tanpa from sekolah where address not like '%, Indonesia';
  raise notice '0063: % sekolah, % nama kembar, % alamat di luar bentuk baku.',
    v_s, v_d, v_tanpa;
  assert v_d = 0, 'masih ada nama sekolah kembar';
end $$;
